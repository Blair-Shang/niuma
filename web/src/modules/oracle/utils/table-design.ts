export interface ParsedDataType {
  base: string
  length?: number
  precision?: number
  scale?: number
  /** 字符型长度语义；BYTE 为库默认，不在字面量中输出。 */
  lengthSemantics?: 'CHAR'
  raw: string
}

export interface DesignColumnDraft {
  __rowKey: string
  originalName: string
  name: string
  /** 完整类型字面量，如 VARCHAR2(255)、NUMBER(18,2) */
  dataType: string
  typeBase: string
  typeLength?: number
  typeScale?: number
  /** 字符型为 CHAR 语义时保留，保存/预览时输出 VARCHAR2(n CHAR)。 */
  typeLengthSemantics?: 'CHAR'
  /** @deprecated Oracle 无 UNSIGNED；保留字段以免旧草稿崩溃 */
  unsigned: boolean
  /** @deprecated Oracle 无 ENUM；保留字段以免旧草稿崩溃 */
  enumValues: string
  nullable: boolean
  defaultExpr: string
  primaryKey: boolean
  /** 对应 GENERATED BY DEFAULT AS IDENTITY */
  autoIncrement: boolean
  comment: string
  removed: boolean
}

export interface DesignIndexDraft {
  __rowKey: string
  originalName: string
  name: string
  columnsText: string
  unique: boolean
  primary: boolean
  /** NORMAL / BITMAP */
  method: string
  removed: boolean
  snapName: string
  snapColumnsText: string
  snapUnique: boolean
  snapMethod: string
}

export interface DesignForeignKeyDraft {
  __rowKey: string
  originalName: string
  name: string
  columnsText: string
  refTable: string
  refColumnsText: string
  onDelete: string
  /** Oracle 不支持 ON UPDATE；保留字段仅作 UI 兼容 */
  onUpdate: string
  removed: boolean
}

let draftCounter = 0
export function nextDraftKey(prefix: string): string {
  return `${prefix}-${++draftCounter}`
}

export function resolveBaseTypeOption(base: string): OracleBaseTypeOption | undefined {
  const upper = base.trim().toUpperCase()
  return ORACLE_BASE_TYPE_OPTIONS.find((o) => o.base.toUpperCase() === upper)
}

export function dataTypeParamKind(base: string): DataTypeParamKind {
  return resolveBaseTypeOption(base)?.kind ?? 'none'
}

export function allowsUnsigned(_base: string): boolean {
  return false
}

