/** 解析 Oracle 类型字符串（支持多词类型 + 精度括号 + BYTE/CHAR 语义）。 */
const CHAR_LENGTH_BASES = new Set(['VARCHAR2', 'CHAR', 'NVARCHAR2', 'NCHAR'])

function supportsCharLengthSemantics(base: string): boolean {
  return CHAR_LENGTH_BASES.has(base.trim().toUpperCase())
}

export function parseDataType(raw: string): ParsedDataType {
  const trimmed = raw.trim().replace(/\s+/g, ' ')
  if (!trimmed) return { base: '', raw }

  const tsTz = trimmed.match(
    /^TIMESTAMP\s*\(\s*(\d+)\s*\)\s+(WITH\s+LOCAL\s+TIME\s+ZONE|WITH\s+TIME\s+ZONE)$/i,
  )
  if (tsTz) {
    const zone = tsTz[2].replace(/\s+/g, ' ').trim().toUpperCase()
    return {
      base: `TIMESTAMP ${zone}`,
      length: parseInt(tsTz[1], 10),
      raw,
    }
  }

  const charUnit = trimmed.match(/^(.+?)\s*\(\s*(\d+)\s+(BYTE|CHAR)\s*\)$/i)
  if (charUnit) {
    const base = charUnit[1].trim().toUpperCase()
    const unit = charUnit[3].toUpperCase()
    return {
      base,
      length: parseInt(charUnit[2], 10),
      lengthSemantics: unit === 'CHAR' ? 'CHAR' : undefined,
      raw,
    }
  }

  const paren = trimmed.match(/^(.+?)\s*\(\s*(\d+)(?:\s*,\s*(\d+))?\s*\)$/i)
  if (paren) {
    const base = paren[1].trim().toUpperCase()
    const first = parseInt(paren[2], 10)
    const second = paren[3] != null ? parseInt(paren[3], 10) : undefined
    if (second !== undefined) {
      return { base, precision: first, scale: second, raw }
    }
    return { base, length: first, raw }
  }

  return { base: trimmed.toUpperCase(), raw }
}

export function buildDataType(
  base: string,
  opts?: {
    length?: number
    scale?: number
    lengthSemantics?: 'CHAR'
  },
): string {
  const opt = resolveBaseTypeOption(base)
  const kind = opt?.kind ?? 'none'
  const core = base.trim().toUpperCase()

  if (kind === 'length' && opts?.length != null) {
    const charSuffix =
      opts.lengthSemantics === 'CHAR' && supportsCharLengthSemantics(core) ? ' CHAR' : ''
    return `${core}(${opts.length}${charSuffix})`
  }
  if (kind === 'precision' && opts?.length != null) {
    return opts.scale != null ? `${core}(${opts.length},${opts.scale})` : `${core}(${opts.length})`
  }
  return core
}

export function syncColumnDataType(col: Pick<
  DesignColumnDraft,
  'typeBase' | 'typeLength' | 'typeScale' | 'typeLengthSemantics'
>): string {
  return buildDataType(col.typeBase, {
    length: col.typeLength,
    scale: col.typeScale,
    lengthSemantics: col.typeLengthSemantics,
  })
}

export function splitDataTypeFields(raw: string): {
  dataType: string
  typeBase: string
  typeLength?: number
  typeScale?: number
  typeLengthSemantics?: 'CHAR'
  unsigned: boolean
  enumValues: string
} {
  const p = parseDataType(raw)
  const known = resolveBaseTypeOption(p.base)
  const typeBase = known?.base ?? p.base
  return {
    dataType: buildDataType(typeBase, {
      length: p.length ?? p.precision,
      scale: p.scale,
      lengthSemantics: p.lengthSemantics,
    }),
    typeBase,
    typeLength: p.length ?? p.precision,
    typeScale: p.scale,
    typeLengthSemantics: p.lengthSemantics,
    unsigned: false,
    enumValues: '',
  }
}

export function parseColumnList(text: string): string[] {
  return text
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
}

export function joinColumnList(cols: string[]): string {
  return cols.map((c) => c.trim()).filter(Boolean).join(', ')
}

export function suggestIndexName(columnsText: string, fallback = 'idx'): string {
  const cols = parseColumnList(columnsText)
  if (cols.length === 0) return fallback
  return `idx_${cols.join('_').slice(0, 48)}`
}

export function isDefaultIndexName(name: string): boolean {
  return !name.trim() || /^idx(_|$)/i.test(name.trim())
}

/** 已带引号 / 关键字 / 数字 / 函数的 DEFAULT，原样输出；其余按字符串字面量加单引号。 */
const ORACLE_DEFAULT_BARE_RE =
  /^(NULL|TRUE|FALSE|SYSDATE|SYSTIMESTAMP|CURRENT_DATE|CURRENT_TIMESTAMP(?:\(\d*\))?|LOCALTIMESTAMP(?:\(\d*\))?|USER|UID|SYS_GUID\(\))$/i
const ORACLE_DEFAULT_NUMBER_RE = /^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?$/

/**
 * 将 UI 中的默认值整理为可写入 DEFAULT 子句的 SQL 片段。
 */
export function formatOracleDefaultExpr(expr: string): string {
  const e = expr.trim()
  if (!e) return ''
  if (
    (e.startsWith("'") && e.endsWith("'")) ||
    (e.startsWith('"') && e.endsWith('"'))
  ) {
    return e
  }
  if (ORACLE_DEFAULT_BARE_RE.test(e)) return e
  if (ORACLE_DEFAULT_NUMBER_RE.test(e)) return e
  if (e.startsWith('(') && e.endsWith(')')) return e
  return `'${e.replace(/'/g, "''")}'`
}

export function columnsEqual(a: DesignColumnDraft, b: DesignColumnDraft): boolean {
  return (
    a.name === b.name &&
    a.dataType === b.dataType &&
    a.nullable === b.nullable &&
    a.defaultExpr === b.defaultExpr &&
    a.comment === b.comment &&
    a.autoIncrement === b.autoIncrement &&
    a.primaryKey === b.primaryKey
  )
}
